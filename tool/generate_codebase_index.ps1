param(
    [string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
)

$ErrorActionPreference = 'Stop'
$docs = Join-Path $Root 'docs'
$generatedPattern = '(\.g\.dart|\.freezed\.dart|\.pb\.dart|\.pbenum\.dart|\.pbjson\.dart|\.pbserver\.dart)$'
$sourceExtensions = @('.dart', '.js', '.ps1', '.kt', '.java', '.swift', '.cpp', '.cc', '.h')
$files = @(
    & git -C $Root -c core.quotepath=false ls-files --cached --others --exclude-standard
) | Sort-Object -Unique
$timestamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss zzz'
$tick = [char]96

function Get-TypeRole([string]$name, [string]$kind) {
    if ($name -match '(Controller|Ctr)$') { return 'page or business state controller' }
    if ($name -match '(Page|View|Panel|Dialog|Sheet)$') { return 'page or visual structure' }
    if ($name -match '(Widget|Button|Card|Item|Tile|Indicator|Painter|Render)') { return 'reusable UI or rendering component' }
    if ($name -match '(Service|Manager|Handler)$') { return 'cross-page service, resource manager, or system coordinator' }
    if ($name -match 'Http$') { return 'network API wrapper for its business domain' }
    if ($name -match '(Model|Info|Data|Entry|State|Result|Response|Request)$') { return 'data structure or state carrier' }
    if ($kind -eq 'enum') { return 'finite state or option set' }
    if ($kind -eq 'extension') { return 'adds convenience behavior to an existing type' }
    if ($kind -eq 'mixin') { return 'behavior shared by multiple classes' }
    if ($kind -eq 'typedef') { return 'callback or type alias' }
    return 'source type; see its file and CODEBASE_REFERENCE.md for boundaries'
}

function Get-CallableRole([string]$name) {
    if ($name -match '^(build|createState)$') { return 'builds UI or state' }
    if ($name -match '^(main|init|initialize|onInit|setup|ensure|register|start)') { return 'starts or initializes state and resources' }
    if ($name -match '^(dispose|close|onClose|stop|cancel|clear|remove|retire|reset)') { return 'stops, releases, or resets state and resources' }
    if ($name -match '^(get|fetch|query|load|read|request|download|sync|check)') { return 'reads, requests, or synchronizes data' }
    if ($name -match '^(set|update|save|write|put|insert|add|mark|record|persist)') { return 'updates, stores, or records state' }
    if ($name -match '^(parse|from|decode|convert|map)') { return 'parses or converts data' }
    if ($name -match '^(toJson|toMap|encode|export)') { return 'serializes or exports data' }
    if ($name -match '^(is|has|should|can|accept|validate|find)') { return 'predicate, validation, or lookup' }
    if ($name -match '(switch|recover|rebuild|resume|retry|refresh)') { return 'switches, recovers, or refreshes runtime state' }
    if ($name -match '^(on|handle|did|enter|exit|toggle|show|hide|open|push|play|pause|seek)') { return 'handles interaction, lifecycle, or playback events' }
    return 'performs one operation in its enclosing type or module'
}

$fileIndex = [System.Collections.Generic.List[string]]::new()
$fileIndex.Add('# PiliPlus complete source file index')
$fileIndex.Add('')
$fileIndex.Add("Generated: $timestamp")
$fileIndex.Add('')
$fileIndex.Add('Generated by tool/generate_codebase_index.ps1. Use CODEBASE_REFERENCE.md for architecture and this file for exact locations.')
$fileIndex.Add('')
$fileIndex.Add("Versioned and non-ignored project file count: $($files.Count)")
$fileIndex.Add('')

foreach ($group in ($files | Group-Object { ($_ -split '/')[0] } | Sort-Object Name)) {
    $fileIndex.Add("## $($group.Name)")
    $fileIndex.Add('')
    foreach ($file in $group.Group) {
        $tag = if ($file -match $generatedPattern -or $file -match 'GeneratedPluginRegistrant') { ' (generated; normally do not edit)' } else { '' }
        $fileIndex.Add('- ' + $tick + $file + $tick + $tag)
    }
    $fileIndex.Add('')
}

$symbolIndex = [System.Collections.Generic.List[string]]::new()
$symbolIndex.Add('# PiliPlus class and function index')
$symbolIndex.Add('')
$symbolIndex.Add("Generated: $timestamp")
$symbolIndex.Add('')
$symbolIndex.Add('Handwritten sources include types and recognizable named functions/methods. Generated protobuf, JSON, and plugin registration files list top-level types only. Local closures, operators, and multiline anonymous functions remain discoverable in source.')
$symbolIndex.Add('')

foreach ($file in $files) {
    $extension = [IO.Path]::GetExtension($file).ToLowerInvariant()
    if ($sourceExtensions -notcontains $extension) { continue }
    $path = Join-Path $Root ($file -replace '/', '\')
    if (-not (Test-Path -LiteralPath $path)) { continue }
    $isGenerated = $file -match $generatedPattern -or $file -match 'GeneratedPluginRegistrant'
    $lines = @(Get-Content -LiteralPath $path -Encoding UTF8)
    $symbols = [System.Collections.Generic.List[string]]::new()
    $declaredTypes = [System.Collections.Generic.HashSet[string]]::new()

    foreach ($sourceLine in $lines) {
        $sourceTrim = $sourceLine.Trim()
        if ($sourceTrim -match '^(?:(?:abstract|base|final|interface|sealed)\s+)*(?:class|mixin|enum|extension)\s+([_A-Za-z][_A-Za-z0-9]*)') {
            [void]$declaredTypes.Add($matches[1])
        }
    }

    for ($i = 0; $i -lt $lines.Count; $i++) {
        $trim = $lines[$i].Trim()
        if (-not $trim -or $trim.StartsWith('//') -or $trim.StartsWith('*')) { continue }
        $kind = $null
        $name = $null

        if ($extension -eq '.dart' -and $trim -match '^(?:(?:abstract|base|final|interface|sealed)\s+)*(class|mixin|enum|extension|typedef)\s+([_A-Za-z][_A-Za-z0-9]*)') {
            $kind = $matches[1]
            $name = $matches[2]
            $symbols.Add('- L' + ($i + 1) + ' - **' + $kind + ' ' + $tick + $name + $tick + '** - ' + (Get-TypeRole $name $kind))
            continue
        }
        if ($extension -in @('.js', '.kt', '.java', '.swift', '.cpp', '.cc', '.h') -and $trim -match '^(?:(?:export|abstract|public|private|protected|internal|final|sealed|data|open|static)\s+)*(class|interface|enum|object|struct|extension)\s+([_A-Za-z][_$A-Za-z0-9]*)') {
            $kind = $matches[1]
            $name = $matches[2]
            $symbols.Add('- L' + ($i + 1) + ' - **' + $kind + ' ' + $tick + $name + $tick + '** - ' + (Get-TypeRole $name $kind))
            continue
        }
        if ($isGenerated) { continue }

        $isDartConstructor = $false
        if ($extension -eq '.dart' -and $trim -match '^(?:const\s+|factory\s+)?([_A-Za-z][_A-Za-z0-9]*)\s*(?:\.[_A-Za-z][_A-Za-z0-9]*)?\s*\(' -and $declaredTypes.Contains($matches[1])) {
            $name = $matches[1]
            $isDartConstructor = $true
        }

        if (-not $isDartConstructor -and $trim -match '^(?:return|await|throw|yield|if|else|for|while|switch|case|const)\b') {
            continue
        }

        if ($isDartConstructor) {
            # Constructor already captured above.
        } elseif ($extension -eq '.dart' -and $trim -match '^(?:(?:static|external|factory|late|final|FutureOr)\s+)*(?:[A-Za-z_][A-Za-z0-9_<>,?.]*\s+)+([_A-Za-z][_A-Za-z0-9]*)\s*\(') {
            $name = $matches[1]
        } elseif ($extension -eq '.dart' -and $trim -match '^([_A-Za-z][_A-Za-z0-9]*)\s*\([^;]*\)\s*(?:async\s*)?(?:\{|=>)') {
            $name = $matches[1]
        } elseif ($extension -eq '.js' -and $trim -match '^(?:async\s+)?function\s+([_$A-Za-z][_$A-Za-z0-9]*)\s*\(') {
            $name = $matches[1]
        } elseif ($extension -eq '.js' -and $trim -match '^(?:const|let|var)\s+([_$A-Za-z][_$A-Za-z0-9]*)\s*=\s*(?:async\s*)?\(') {
            $name = $matches[1]
        } elseif ($extension -eq '.ps1' -and $trim -match '^function\s+([_A-Za-z][_A-Za-z0-9-]*)') {
            $name = $matches[1]
        } elseif ($extension -eq '.kt' -and $trim -match '^(?:(?:override|public|private|protected|internal|suspend|inline|operator|tailrec)\s+)*fun\s+([_A-Za-z][_A-Za-z0-9]*)\s*\(') {
            $name = $matches[1]
        } elseif ($extension -eq '.swift' -and $trim -match '^(?:(?:override|public|private|fileprivate|internal|open|static|class|mutating)\s+)*func\s+([_A-Za-z][_A-Za-z0-9]*)\s*\(') {
            $name = $matches[1]
        } elseif ($extension -in @('.java', '.cpp', '.cc', '.h') -and $trim -match '^(?:(?:override|public|private|protected|internal|static|final|synchronized|native|abstract|virtual|inline|constexpr|extern)\s+)*(?:[A-Za-z_][A-Za-z0-9_<>,?.:\[\]*&]*\s+)+([_A-Za-z][_A-Za-z0-9]*)\s*\(') {
            $name = $matches[1]
        }

        if ($name -and $name -notmatch '^(if|for|while|switch|catch|return|assert|super|this|Function)$') {
            $signature = $trim.Replace($tick, "'")
            if ($signature.Length -gt 160) { $signature = $signature.Substring(0, 157) + '...' }
            $symbols.Add('- L' + ($i + 1) + ' - ' + $tick + $signature + $tick + ' - ' + (Get-CallableRole $name))
        }
    }

    if ($symbols.Count -gt 0) {
        $symbolIndex.Add('## ' + $tick + $file + $tick)
        $symbolIndex.Add('')
        foreach ($symbol in $symbols) { $symbolIndex.Add($symbol) }
        $symbolIndex.Add('')
    }
}

[IO.File]::WriteAllLines((Join-Path $docs 'SOURCE_FILE_INDEX.md'), $fileIndex, [Text.UTF8Encoding]::new($false))
[IO.File]::WriteAllLines((Join-Path $docs 'SYMBOL_INDEX.md'), $symbolIndex, [Text.UTF8Encoding]::new($false))

Write-Output "files=$($files.Count) fileIndexLines=$($fileIndex.Count) symbolIndexLines=$($symbolIndex.Count)"
